// сам логотип в нужном «материале»
export function Logotype({ v = 'flat', h = 20, className = '' }: { v?: V; h?: number; className?: string }) {
  const body = (() => {
    switch (v) {
      case 'gold': return <>
        <g transform="translate(0 16)" opacity=".85"><Glyphs fill="#1a0f02" /></g>
        <Glyphs fill="url(#qc-gold)" />
        <Outline stroke="#fff6c8" w={7} op={0.55} />
      </>
      case 'neon': return <g className="qc-tube">
        <g filter="url(#qc-blur2)" opacity=".85"><Outline stroke="#1fd18f" w={60} /></g>
        <g filter="url(#qc-blur1)"><Outline stroke="#5dffc0" w={26} /></g>
        <Outline stroke="#e4fff3" w={13} />
      </g>
      case 'thread': return <>
        <g transform="translate(0 14)" opacity=".45"><Glyphs fill="#06140e" /></g>
        <Glyphs fill="url(#qc-thread)" />
        <Outline stroke="#fbe9a6" w={7} dash="34 20" op={0.95} />
      </>
      case 'paint': return <g filter="url(#qc-worn)"><Glyphs fill="#f4f6f4" /></g>
      case 'foil': return <>
        <Glyphs fill="url(#qc-foil)" />
        <Outline stroke="#ffffff" w={6} op={0.55} />
      </>
      case 'ink': return <Glyphs fill="currentColor" />
      case 'iron': return <>
        <g transform="translate(0 12)" opacity=".7"><Glyphs fill="#07030c" /></g>
        <Glyphs fill="#c9a24f" />
        <Outline stroke="#f1d58a" w={6} op={0.6} />
      </>
      default: return <Glyphs fill="#eafff6" arrow="#59d49a" />
    }
  })()
  return <svg className={`logotype lt-${v} ${className}`} viewBox={VB} height={h} width={Math.round(h * AR / 1090)} role="img" aria-label="QcUp">{body}</svg>
}

